/// Collapse Whisper repetition loops:
/// - Single-character loops (`斤斤斤斤叫` -> `惊声尖叫`, `啊啊啊啊` -> `啊`, `的的的的` -> `的`)
/// - Multi-character CJK word loops (`真实真实真实真实` -> `真实`, `语言语言是语言语言语言` -> `语言`)
/// - Latin word/phrase repetition loops (`real real real real` -> `real`, `language language language` -> `language`)
pub fn collapse_asr_repetitions(input: &str) -> String {
    if input.is_empty() {
        return String::new();
    }
    let mut s = input.to_string();

    // 1. Specific scream/noise-induced repetition traps before `叫` / `喊`
    for pat in ["斤斤斤斤叫", "斤斤斤叫", "斤斤叫", "惊惊惊惊叫", "惊惊叫", "金金金金叫"] {
        if s.contains(pat) {
            s = s.replace(pat, "惊声尖叫");
        }
    }
    if s.contains("语言语言是语言") || s.contains("语言语言语言") {
        while s.contains("语言语言是语言") {
            s = s.replace("语言语言是语言", "语言");
        }
        while s.contains("语言语言") {
            s = s.replace("语言语言", "语言");
        }
        if s.ends_with("语言语，") {
            s = s.trim_end_matches("语言语，").to_string() + "语言，";
        } else if s.ends_with("语言语") {
            s = s.trim_end_matches("语言语").to_string() + "语言";
        }
    }

    // 2. General 3+ consecutive single-character repetition collapse (except legitimate numbers/punctuation)
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::with_capacity(s.len());
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let mut run = 1usize;
        while i + run < chars.len() && chars[i + run] == c {
            run += 1;
        }
        if run >= 3 && !c.is_ascii_digit() && c != '.' && c != '…' {
            out.push(c);
            i += run;
        } else {
            for _ in 0..run {
                out.push(c);
            }
            i += run;
        }
    }

    // 3. Multi-character CJK n-gram (2..=4 chars) repetition collapse (`真实真实真实真实` -> `真实`, `将将` -> `将`)
    let mut cjk_chars: Vec<char> = out.chars().collect();
    for gram_len in [2usize, 3, 4] {
        let mut cleaned = Vec::with_capacity(cjk_chars.len());
        let mut idx = 0;
        while idx < cjk_chars.len() {
            if idx + gram_len * 3 <= cjk_chars.len() {
                let pat = &cjk_chars[idx..idx + gram_len];
                if pat.iter().all(|&c| (0x4E00..=0x9FFF).contains(&(c as u32))) {
                    let mut reps = 1usize;
                    while idx + (reps + 1) * gram_len <= cjk_chars.len()
                        && &cjk_chars[idx + reps * gram_len..idx + (reps + 1) * gram_len] == pat
                    {
                        reps += 1;
                    }
                    if reps >= 3 {
                        cleaned.extend_from_slice(pat);
                        idx += reps * gram_len;
                        continue;
                    }
                }
            }
            cleaned.push(cjk_chars[idx]);
            idx += 1;
        }
        cjk_chars = cleaned;
    }
    let mut res: String = cjk_chars.into_iter().collect();
    // Collapse accidental double `您将将` -> `您将`
    if res.contains("您将将") {
        res = res.replace("您将将", "您将");
    }

    // 4. Space-delimited Latin word repetition collapse (3+ identical consecutive words -> 1 word)
    if res.chars().any(|c| c.is_ascii_alphabetic()) {
        let tokens: Vec<&str> = res.split(' ').collect();
        if tokens.len() >= 3 {
            let mut dedup_tokens: Vec<&str> = Vec::with_capacity(tokens.len());
            let mut ti = 0;
            while ti < tokens.len() {
                let w = tokens[ti];
                let w_bare = w.trim_matches(|c: char| !c.is_alphabetic());
                let mut run = 1usize;
                if !w_bare.is_empty() {
                    while ti + run < tokens.len() {
                        let next_bare = tokens[ti + run].trim_matches(|c: char| !c.is_alphabetic());
                        if next_bare.eq_ignore_ascii_case(w_bare) {
                            run += 1;
                        } else {
                            break;
                        }
                    }
                }
                if run >= 3 {
                    dedup_tokens.push(tokens[ti + run - 1]);
                    ti += run;
                } else {
                    dedup_tokens.push(w);
                    ti += 1;
                }
            }
            res = dedup_tokens.join(" ");
        }
    }

    res
}

