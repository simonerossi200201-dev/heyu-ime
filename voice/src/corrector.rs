//! Stage 3 & 4 of HEYU High-Precision ASR Pipeline:
//! 1. Traditional-to-Simplified Chinese normalization (`to_simplified_zh`) for multilingual `large-v3`
//!    (which frequently emits Traditional characters on Taiwanese/HK/overseas Chinese audio).
//! 2. Repetition hallucination & background-scream loop suppression (`collapse_asr_repetitions`).
//! 3. Pinyin-Guided Contextual Homophone & Southern/Taiwanese Mandarin (`z/zh`, `c/ch`, `s/sh`, `in/ing`, `en/eng`)
//!    Disambiguation (`correct_zh_homophones_and_collocations`).
//! 4. Rolling Session Context & Cross-Sentence Entity Alignment (`SessionContext`):
//!    maintains the rolling 220-char prompt context fed into Whisper's decoder and aligns repeated
//!    proper nouns / domain entities across chunks.

/// Session-level rolling memory across continuous streaming segments.
#[derive(Clone, Debug, Default)]
pub struct SessionContext {
    /// Rolling transcript history (last ~240 characters) passed into Whisper's `initial_prompt`
    /// so the 32-layer decoder maintains topic, entity, and terminology continuity across chunks.
    pub rolling_text: String,
    /// Multi-character domain entities discovered earlier in the session (e.g. "十字架", "瓜亚基尔", "神父").
    pub active_entities: Vec<String>,
}

impl SessionContext {
    pub fn new() -> Self {
        Self {
            rolling_text: String::new(),
            active_entities: Vec::new(),
        }
    }

    pub fn clear(&mut self) {
        self.rolling_text.clear();
        self.active_entities.clear();
    }

    /// Record a newly committed clean sentence into the rolling context and extract salient entities.
    pub fn observe_committed(&mut self, text: &str) {
        let trimmed = text.trim();
        if trimmed.is_empty() {
            return;
        }
        self.rolling_text.push_str(trimmed);
        let chars: Vec<char> = self.rolling_text.chars().collect();
        if chars.len() > 220 {
            self.rolling_text = chars[chars.len() - 220..].iter().collect();
        }
        for ent in [
            "十字架",
            "瓜亚基尔",
            "厄瓜多尔",
            "厄瓜多",
            "圣母堂",
            "桑切斯",
            "总教区",
            "神父",
            "弥撒",
            "救护车",
            "后脑勺",
            "道成肉身",
            "受造之物",
            "造物主",
            "恩典时代",
            "主耶稣",
        ] {
            if trimmed.contains(ent) && !self.active_entities.iter().any(|e| e == ent) {
                self.active_entities.push(ent.to_string());
            }
        }
    }

    /// Return the recent rolling transcript tail (up to 180 chars) to feed into Whisper's `initial_prompt`.
    pub fn recent_prompt_tail(&self) -> &str {
        &self.rolling_text
    }

    /// Deduplicate boundary syllable or word overlap when a fast continuous speech stream was split across two chunks
    /// (e.g. previous chunk ended with `马上！` and new chunk starts with `马上就能用上了`,
    /// or previous English chunk ended with `concentrate,` and new starts with `On achieving` / `concentrate on achieving`).
    pub fn dedup_boundary_prefix(&self, next_seg: &str) -> String {
        let prev_bare = self.rolling_text.trim_end_matches(|c: char| {
            matches!(c, '，' | '。' | '？' | '！' | '；' | '：' | '、' | ',' | '.' | '?' | '!' | ' ')
        });
        let next_trim = next_seg.trim_start();
        if prev_bare.is_empty() || next_trim.is_empty() {
            return next_seg.to_string();
        }
        // 1. Word-level boundary overlap for Latin scripts (English / Spanish / Italian):
        // Check if the last 1, 2, or 3 space-separated words of `prev_bare` match the first 1, 2, or 3 words of `next_trim` (case-insensitive)
        let prev_words: Vec<&str> = prev_bare.split_whitespace().collect();
        let next_words: Vec<&str> = next_trim.split_whitespace().collect();
        if !prev_words.is_empty() && next_words.len() > 1 {
            for w_k in [3usize, 2, 1] {
                if prev_words.len() >= w_k && next_words.len() > w_k {
                    let match_words = (0..w_k).all(|idx| {
                        let pw = prev_words[prev_words.len() - w_k + idx]
                            .trim_matches(|c: char| !c.is_alphabetic());
                        let nw = next_words[idx].trim_matches(|c: char| !c.is_alphabetic());
                        !pw.is_empty() && pw.eq_ignore_ascii_case(nw) && (w_k >= 2 || pw.len() >= 3)
                    });
                    if match_words {
                        return next_words[w_k..].join(" ");
                    }
                }
            }
        }

        // 2. Character-level boundary overlap for CJK scripts:
        let prev_chars: Vec<char> = prev_bare.chars().collect();
        let next_chars: Vec<char> = next_trim.chars().collect();
        // Check 3-char, 2-char, and 1-char boundary overlap
        for k in [3usize, 2, 1] {
            if prev_chars.len() >= k && next_chars.len() > k {
                let tail_k = &prev_chars[prev_chars.len() - k..];
                let head_k = &next_chars[..k];
                if tail_k == head_k && tail_k.iter().all(|c| !c.is_ascii_alphabetic()) {
                    // For k == 1, only strip if the repeated character is not a deliberate reduplication (like `拍拍`, `看看`, `试试`)
                    let ch = head_k[0];
                    let next_after = next_chars.get(1).copied().unwrap_or(' ');
                    if k >= 2 || (ch != next_after && matches!(ch, '是' | '像' | '的' | '了' | '在' | '有' | '就' | '都' | '也' | '还' | '人' | '能')) {
                        return next_chars[k..].iter().collect();
                    }
                }
            }
        }
        next_seg.to_string()
    }
}

/// Convert Traditional Chinese characters and Taiwan/HK regional character variants to standard Simplified Chinese.
pub fn to_simplified_zh(input: &str) -> String {
    let mut out = String::with_capacity(input.len());
    for c in input.chars() {
        out.push(trad_to_simp_char(c));
    }
    out
}

